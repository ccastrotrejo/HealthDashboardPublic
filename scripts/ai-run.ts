#!/usr/bin/env tsx
/**
 * Single entry point for every AI generator.
 *
 * Exists so the eight scheduled workflows can share one reusable workflow file
 * instead of eight near-identical 63-line copies of the same checkout → install
 * → generate → rebase-retry-push sequence.
 *
 * Also carries the failure policy the pipeline was missing. Every generator
 * degrades to a deterministic template rather than throwing, which is correct
 * for availability but meant a green checkmark said nothing about whether any
 * analysis actually happened. With `--strict` (used by CI) a template fallback
 * exits non-zero, so a silently degrading provider surfaces as a failed run.
 *
 * Usage:
 *   pnpm ai insights
 *   pnpm ai insights --print-prompt
 *   pnpm ai all --strict
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dataPath } from './lib/storage.js';

const TASKS = {
  insights: { script: 'ai-insights.ts', file: 'insights.json' },
  'today-debrief': { script: 'ai-today-debrief.ts', file: 'today-debrief.json' },
  coach: { script: 'ai-coach.ts', file: 'coach.json' },
  'weekly-review': { script: 'ai-weekly-review.ts', file: 'weekly-review.json' },
  'monthly-patterns': { script: 'ai-monthly-patterns.ts', file: 'monthly-patterns.json' },
  'race-week': { script: 'ai-race-week.ts', file: 'race-week.json' },
  'post-race': { script: 'ai-post-race.ts', file: 'post-race.json' },
  calibration: { script: 'ai-calibration.ts', file: 'calibration.json' },
} as const;

type TaskName = keyof typeof TASKS;

const scriptsDir = fileURLToPath(new URL('.', import.meta.url));

function runTask(name: TaskName, printPrompt: boolean): { ok: boolean; template: boolean } {
  const task = TASKS[name];
  console.log(`\n─── ${name} ───`);

  const res = spawnSync('tsx', [resolve(scriptsDir, task.script)], {
    stdio: 'inherit',
    env: printPrompt ? { ...process.env, PRINT_PROMPT: '1' } : process.env,
  });

  if (res.status !== 0) {
    console.error(`✗ ${name} exited ${res.status}`);
    return { ok: false, template: false };
  }
  if (printPrompt) return { ok: true, template: false };

  // Inspect the artifact to see whether real analysis happened or the
  // deterministic fallback fired.
  const path = dataPath(task.file);
  if (!existsSync(path)) {
    // Race-week and post-race legitimately produce nothing when no race is near.
    console.log(`· ${name} produced no artifact (nothing to do)`);
    return { ok: true, template: false };
  }
  try {
    const artifact = JSON.parse(readFileSync(path, 'utf8')) as {
      model?: string;
      isTemplate?: boolean;
      fallbackReason?: string;
      dataStale?: boolean;
      snapshotAgeHours?: number;
    };
    if (artifact.dataStale) {
      console.warn(
        `⚠ ${name} ran against a snapshot ${artifact.snapshotAgeHours}h old — artifact marked stale`,
      );
    }
    if (artifact.isTemplate || artifact.model === 'template') {
      console.warn(`⚠ ${name} fell back to template: ${artifact.fallbackReason ?? 'unknown'}`);
      return { ok: true, template: true };
    }
    console.log(`✓ ${name} generated by ${artifact.model}`);
    return { ok: true, template: false };
  } catch {
    console.error(`✗ ${name} wrote an unreadable artifact`);
    return { ok: false, template: false };
  }
}

const args = process.argv.slice(2);
const strict = args.includes('--strict');
const printPrompt = args.includes('--print-prompt');
const requested = args.filter((a) => !a.startsWith('--'));

if (!requested.length) {
  console.error('Usage: pnpm ai <task|all> [--strict] [--print-prompt]');
  console.error(`Tasks: ${Object.keys(TASKS).join(', ')}`);
  process.exit(2);
}

const names: TaskName[] =
  requested[0] === 'all'
    ? (Object.keys(TASKS) as TaskName[])
    : requested.map((r) => {
        if (!(r in TASKS)) {
          console.error(`Unknown task "${r}". Known: ${Object.keys(TASKS).join(', ')}`);
          process.exit(2);
        }
        return r as TaskName;
      });

let failed = 0;
let templated = 0;
for (const name of names) {
  const result = runTask(name, printPrompt);
  if (!result.ok) failed++;
  if (result.template) templated++;
}

console.log(
  `\n${names.length} task(s): ${names.length - failed - templated} generated, ${templated} template, ${failed} failed`,
);

if (failed > 0) process.exit(1);
if (strict && templated > 0) {
  console.error(
    'Strict mode: at least one task degraded to its deterministic template. ' +
      'Check the LLM provider configuration — a green run that produced no analysis is a failure.',
  );
  process.exit(1);
}
