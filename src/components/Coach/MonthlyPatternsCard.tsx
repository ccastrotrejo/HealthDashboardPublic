import { Badge } from '@astryxdesign/core/Badge';
import { Heading } from '@astryxdesign/core/Heading';
import type { MonthlyPatternsBlock } from '../../lib/types';
import { Card } from '../shared/Card';
import { AiCardMeta } from './AiCardMeta';
import { lookup } from '../../lib/aiMeta';

interface Props {
  data: MonthlyPatternsBlock;
}

const CONFIDENCE_BADGE = {
  high: 'green',
  medium: 'neutral',
  low: 'neutral',
} as const;

function fmtForMonth(iso: string): string {
  const d = new Date(iso + 'T12:00:00Z');
  return d.toLocaleDateString(undefined, {
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  });
}

/**
 * Monthly pattern recap generated by the `health-dashboard-monthly-patterns`
 * scheduled task (runs 1st of each month). Surfaces 3–5 multi-week patterns
 * an attentive coach would spot — adaptations, regressions, correlations.
 */
export function MonthlyPatternsCard({ data }: Props) {
  return (
    <Card
      title={`Monthly patterns · ${fmtForMonth(data.forMonth)}`}
      subtitle="AI · multi-week pattern detection"
      className="col-span-full"
      right={<AiCardMeta data={data} artifact="monthly-patterns" />}
    >
      <p className="mb-4 text-base font-medium text-ink-900">{data.headline}</p>

      <ul className="space-y-3">
        {data.patterns.map((p, i) => {
          const variant = lookup<'green' | 'neutral'>(CONFIDENCE_BADGE, p.confidence, 'neutral');
          return (
            <li key={i} className="border-t border-border pt-4">
              <header className="mb-1.5 flex flex-wrap items-baseline gap-2">
                <Heading level={4} className="text-sm font-semibold text-ink-900">
                  {p.title}
                </Heading>
                <Badge variant={variant} label={`${p.confidence} confidence`} />
                {p.sources && p.sources.length > 0 && (
                  <span className="text-xs text-ink-500">· {p.sources.join(' + ')}</span>
                )}
              </header>
              <p className="max-w-prose text-sm leading-relaxed text-ink-700">{p.body}</p>
            </li>
          );
        })}
      </ul>
    </Card>
  );
}
